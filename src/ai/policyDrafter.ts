/**
 * Analyzes differences between active and proposed policies field by field.
 * Every known policy field is classified as TIGHTENED, RELAXED, or UNCHANGED.
 * Throws PolicyDrafterError if an unknown field is encountered.
 */
export function analyzePolicyDiff(
  active: Omit<PolicyDocument, 'version'>,
  proposed: Omit<PolicyDocument, 'version'>
): {
  diff: PolicyDiffItem[];
  hasRelaxations: boolean;
  relaxations: string[];
} {
  // 1. Validate that no unknown fields exist in active or proposed
  for (const key of Object.keys(active)) {
    if (key === 'version') continue;
    if (!KNOWN_POLICY_FIELDS.has(key)) {
      throw new PolicyDrafterError(
        'UNCLASSIFIABLE_FIELD',
        `Active policy contains unknown field '${key}' that cannot be safely classified`
      );
    }
  }

  for (const key of Object.keys(proposed)) {
    if (key === 'version') continue;
    if (!KNOWN_POLICY_FIELDS.has(key)) {
      throw new PolicyDrafterError(
        'UNCLASSIFIABLE_FIELD',
        `Proposed policy contains unknown field '${key}' that cannot be safely classified`
      );
    }
  }

  const diffItems: PolicyDiffItem[] = [];
  const relaxations: string[] = [];

  // Helper to record diff
  function record(
    field: string,
    label: string,
    activeValue: unknown,
    proposedValue: unknown,
    changeType: FieldChangeType,
    explanation: string,
    isRelaxation: boolean
  ): void {
    diffItems.push({
      field,
      label,
      activeValue,
      proposedValue,
      changeType,
      explanation,
      isRelaxation,
    });
    if (isRelaxation) {
      relaxations.push(explanation);
    }
  }

  // 1. auto_limit_minor
  {
    const act = active.auto_limit_minor;
    const prop = proposed.auto_limit_minor;
    if (prop < act) {
      record(
        'auto_limit_minor',
        'Auto-Approve Ceiling',
        act,
        prop,
        'TIGHTENED',
        `Auto-approve limit decreased from ${act} to ${prop} minor units (more payments held for human approval).`,
        false
      );
    } else if (prop > act) {
      record(
        'auto_limit_minor',
        'Auto-Approve Ceiling',
        act,
        prop,
        'RELAXED',
        `Auto-approve limit increased from ${act} to ${prop} minor units (more payments execute automatically without human approval).`,
        true
      );
    } else {
      record(
        'auto_limit_minor',
        'Auto-Approve Ceiling',
        act,
        prop,
        'UNCHANGED',
        `Auto-approve limit unchanged (${act} minor units).`,
        false
      );
    }
  }

  // 2. hard_cap_minor
  {
    const act = active.hard_cap_minor;
    const prop = proposed.hard_cap_minor;
    if (prop < act) {
      record(
        'hard_cap_minor',
        'Hard Cap Ceiling',
        act,
        prop,
        'TIGHTENED',
        `Hard cap ceiling decreased from ${act} to ${prop} minor units (stricter limit on maximum payment size).`,
        false
      );
    } else if (prop > act) {
      record(
        'hard_cap_minor',
        'Hard Cap Ceiling',
        act,
        prop,
        'RELAXED',
        `Hard cap ceiling increased from ${act} to ${prop} minor units (larger individual payments allowed).`,
        true
      );
    } else {
      record(
        'hard_cap_minor',
        'Hard Cap Ceiling',
        act,
        prop,
        'UNCHANGED',
        `Hard cap ceiling unchanged (${act} minor units).`,
        false
      );
    }
  }

  // 3. agent_daily_budget_minor
  {
    const act = active.agent_daily_budget_minor;
    const prop = proposed.agent_daily_budget_minor;
    if (prop < act) {
      record(
        'agent_daily_budget_minor',
        'Agent Daily Budget',
        act,
        prop,
        'TIGHTENED',
        `Agent daily budget decreased from ${act} to ${prop} minor units.`,
        false
      );
    } else if (prop > act) {
      record(
        'agent_daily_budget_minor',
        'Agent Daily Budget',
        act,
        prop,
        'RELAXED',
        `Agent daily budget increased from ${act} to ${prop} minor units (agents can spend more per rolling 24h).`,
        true
      );
    } else {
      record(
        'agent_daily_budget_minor',
        'Agent Daily Budget',
        act,
        prop,
        'UNCHANGED',
        `Agent daily budget unchanged (${act} minor units).`,
        false
      );
    }
  }

  // 4. global_daily_budget_minor
  {
    const act = active.global_daily_budget_minor;
    const prop = proposed.global_daily_budget_minor;
    if (prop < act) {
      record(
        'global_daily_budget_minor',
        'Global Daily Budget',
        act,
        prop,
        'TIGHTENED',
        `Global daily budget decreased from ${act} to ${prop} minor units.`,
        false
      );
    } else if (prop > act) {
      record(
        'global_daily_budget_minor',
        'Global Daily Budget',
        act,
        prop,
        'RELAXED',
        `Global daily budget increased from ${act} to ${prop} minor units (total firewall spend ceiling increased).`,
        true
      );
    } else {
      record(
        'global_daily_budget_minor',
        'Global Daily Budget',
        act,
        prop,
        'UNCHANGED',
        `Global daily budget unchanged (${act} minor units).`,
        false
      );
    }
  }

  // 5. velocity
  {
    const act = active.velocity;
    const prop = proposed.velocity;
    if (act.max_requests === prop.max_requests && act.window_minutes === prop.window_minutes) {
      record(
        'velocity',
        'Velocity Limit',
        act,
        prop,
        'UNCHANGED',
        `Velocity limit unchanged (${act.max_requests} requests per ${act.window_minutes}m).`,
        false
      );
    } else if (prop.max_requests <= act.max_requests && prop.window_minutes >= act.window_minutes) {
      // Strictly tightened: fewer or equal requests allowed over a wider or equal window
      record(
        'velocity',
        'Velocity Limit',
        act,
        prop,
        'TIGHTENED',
        `Velocity limit strictly tightened: ceiling reduced from ${act.max_requests} req/${act.window_minutes}m to ${prop.max_requests} req/${prop.window_minutes}m.`,
        false
      );
    } else if (prop.max_requests >= act.max_requests && prop.window_minutes <= act.window_minutes) {
      // Strictly relaxed: more or equal requests allowed over a narrower or equal window
      record(
        'velocity',
        'Velocity Limit',
        act,
        prop,
        'RELAXED',
        `Velocity limit strictly relaxed: ceiling expanded from ${act.max_requests} req/${act.window_minutes}m to ${prop.max_requests} req/${prop.window_minutes}m.`,
        true
      );
    } else if (prop.max_requests > act.max_requests && prop.window_minutes > act.window_minutes) {
      // Incomparable / Mixed: Burst capacity increased (relaxation) despite longer cooldown window
      record(
        'velocity',
        'Velocity Limit',
        act,
        prop,
        'RELAXED',
        `Velocity limit modified with increased burst capacity: max requests increased from ${act.max_requests} to ${prop.max_requests} (cooldown window also lengthened from ${act.window_minutes}m to ${prop.window_minutes}m).`,
        true
      );
    } else {
      // Incomparable / Mixed: prop.max_requests < act.max_requests AND prop.window_minutes < act.window_minutes
      // Shorter cooldown window allows faster rate reset (relaxation) despite lower burst capacity
      record(
        'velocity',
        'Velocity Limit',
        act,
        prop,
        'RELAXED',
        `Velocity limit modified with shortened cooldown window: lookback window decreased from ${act.window_minutes}m to ${prop.window_minutes}m (allows faster rate reset), though burst ceiling lowered from ${act.max_requests} to ${prop.max_requests}.`,
        true
      );
    }
  }

  // 6. duplicate_window_minutes
  {
    const act = active.duplicate_window_minutes;
    const prop = proposed.duplicate_window_minutes;
    if (prop > act) {
      record(
        'duplicate_window_minutes',
        'Duplicate Window',
        act,
        prop,
        'TIGHTENED',
        `Duplicate suppression window increased from ${act}m to ${prop}m (longer replay protection).`,
        false
      );
    } else if (prop < act) {
      record(
        'duplicate_window_minutes',
        'Duplicate Window',
        act,
        prop,
        'RELAXED',
        `Duplicate suppression window decreased from ${act}m to ${prop}m (shorter replay protection).`,
        true
      );
    } else {
      record(
        'duplicate_window_minutes',
        'Duplicate Window',
        act,
        prop,
        'UNCHANGED',
        `Duplicate suppression window unchanged (${act}m).`,
        false
      );
    }
  }

  // 7. new_vendor_action
  {
    const act = active.new_vendor_action;
    const prop = proposed.new_vendor_action;
    if (act === prop) {
      record(
        'new_vendor_action',
        'Unverified Vendor Action',
        act,
        prop,
        'UNCHANGED',
        `Unverified vendor action unchanged (${act}).`,
        false
      );
    } else if (act === 'HOLD' && prop === 'DENY') {
      record(
        'new_vendor_action',
        'Unverified Vendor Action',
        act,
        prop,
        'TIGHTENED',
        'Unverified vendor action changed from HOLD to DENY (strict rejection without review option).',
        false
      );
    } else if (act === 'DENY' && prop === 'HOLD') {
      record(
        'new_vendor_action',
        'Unverified Vendor Action',
        act,
        prop,
        'RELAXED',
        'Unverified vendor action changed from DENY to HOLD (unverified vendors can now be held for review rather than denied).',
        true
      );
    }
  }

  // 8. hold_ttl_minutes
  {
    const act = active.hold_ttl_minutes;
    const prop = proposed.hold_ttl_minutes;
    if (prop < act) {
      record(
        'hold_ttl_minutes',
        'Hold TTL',
        act,
        prop,
        'TIGHTENED',
        `Approval hold operational review window decreased from ${act}m to ${prop}m (shorter exposure duration for outstanding PayPal authorizations; unattended holds expire and fail closed sooner).`,
        false
      );
    } else if (prop > act) {
      record(
        'hold_ttl_minutes',
        'Hold TTL',
        act,
        prop,
        'RELAXED',
        `Approval hold operational review window increased from ${act}m to ${prop}m (longer exposure duration for outstanding PayPal authorizations and review tokens before failing closed).`,
        true
      );
    } else {
      record(
        'hold_ttl_minutes',
        'Hold TTL',
        act,
        prop,
        'UNCHANGED',
        `Approval hold operational review window unchanged (${act}m).`,
        false
      );
    }
  }

  // 9. currency_allowlist
  {
    const act = [...active.currency_allowlist].sort();
    const prop = [...proposed.currency_allowlist].sort();
    const actSet = new Set(act);
    const propSet = new Set(prop);

    const added = prop.filter((c) => !actSet.has(c));
    const removed = act.filter((c) => !propSet.has(c));

    if (added.length === 0 && removed.length === 0) {
      record(
        'currency_allowlist',
        'Currency Allowlist',
        act,
        prop,
        'UNCHANGED',
        `Currency allowlist unchanged ([${act.join(', ')}]).`,
        false
      );
    } else if (added.length > 0) {
      record(
        'currency_allowlist',
        'Currency Allowlist',
        act,
        prop,
        'RELAXED',
        `Currency allowlist expanded: added [${added.join(', ')}]${
          removed.length > 0 ? `, removed [${removed.join(', ')}]` : ''
        }.`,
        true
      );
    } else {
      record(
        'currency_allowlist',
        'Currency Allowlist',
        act,
        prop,
        'TIGHTENED',
        `Currency allowlist restricted: removed [${removed.join(', ')}].`,
        false
      );
    }
  }

  return {
    diff: diffItems,
    hasRelaxations: relaxations.length > 0,
    relaxations,
  };
}

