/**
 * Recursively sorts object keys for deterministic canonical JSON serialization.
 */
function sortKeys(value: unknown): unknown {
  if (value === null || typeof value !== 'object') {
    return value;
  }
  if (Array.isArray(value)) {
    return value.map(sortKeys);
  }
  const obj = value as Record<string, unknown>;
  const sortedKeys = Object.keys(obj).sort();
  const result: Record<string, unknown> = {};
  for (const key of sortedKeys) {
    result[key] = sortKeys(obj[key]);
  }
  return result;
}

/**
 * Serializes proposal to canonical JSON bound to baseVersion and proposed rules.
 */
export function canonicalizeProposal(
  baseVersion: number,
  proposedRules: Omit<PolicyDocument, 'version'>
): string {
  // Normalize by stripping version if present on proposed rules
  const { version: _v, ...rulesClean } = proposedRules as Record<string, unknown>;
  const canonicalObj = {
    base_version: baseVersion,
    rules: sortKeys(rulesClean),
  };
  return JSON.stringify(canonicalObj);
}

/**
 * Computes canonical SHA-256 integrity hash for a proposal.
 * Note: This hash is an integrity identifier, NOT proof of authorization.
 */
export function computeProposalHash(
  baseVersion: number,
  proposedRules: Omit<PolicyDocument, 'version'>
): string {
  const canonicalJson = canonicalizeProposal(baseVersion, proposedRules);
  return crypto.createHash('sha256').update(canonicalJson, 'utf8').digest('hex');
}

